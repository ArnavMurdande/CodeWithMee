const operationById = new Map(operations.map((entry) => [entry.id, entry]));
if (operationById.size !== operations.length)
  throw new Error('Duplicate API operation identifier.');

function getOperation(id) {
  const found = operationById.get(id);
  if (!found) throw new Error(`Unknown API operation: ${id}`);
  return found;
}

