const SECURITY = Object.freeze({
  BEARER: Object.freeze([{ bearerAuth: [] }]),
  OPTIONAL_BEARER: Object.freeze([{}, { bearerAuth: [] }]),
  PUBLIC: Object.freeze([]),
  REFRESH_CSRF: Object.freeze([{ csrfHeader: [], refreshCookie: [] }]),
});

function operation({
  acceptsBody = false,
  id,
  method,
  path,
  request,
  response,
  security = SECURITY.BEARER,
  status = 200,
  summary,
  tags,
}) {
  return Object.freeze({
    acceptsBody,
    id,
    method,
    path,
    request,
    response,
    security,
    status,
    summary,
    tags: Object.freeze(tags),
  });
}

